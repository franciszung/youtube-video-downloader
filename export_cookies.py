#!/usr/bin/env python3
"""
通过 Edge DevTools Protocol (CDP) 抓 YouTube cookies 并保存为 yt-dlp 兼容的 Netscape 格式。
用法: python export_cookies.py [output_path]
"""
import json
import os
import sys
import time
from urllib.request import urlopen, Request

import websocket  # pip install websocket-client


def get_tabs(port=9222):
    """列出 Edge 所有 tabs"""
    url = f"http://127.0.0.1:{port}/json/list"
    with urlopen(url, timeout=10) as r:
        return json.loads(r.read().decode("utf-8"))


def find_youtube_tab(tabs):
    """找 YouTube tab (排除 service worker)"""
    for t in tabs:
        if t.get("type") != "page":
            continue
        url = t.get("url", "")
        if "youtube.com" in url or "google.com" in url:
            return t
    return None


def get_cookies_via_cdp(ws_url, urls):
    """通过 WebSocket 调 Network.getCookies"""
    ws = websocket.create_connection(ws_url, timeout=30)
    try:
        # Enable Network domain
        ws.send(json.dumps({"id": 1, "method": "Network.enable"}))
        ws.recv()  # 丢弃 ack

        # Get cookies
        ws.send(json.dumps({
            "id": 2,
            "method": "Network.getCookies",
            "params": {"urls": urls}
        }))
        result = json.loads(ws.recv())
    finally:
        ws.close()

    if "error" in result:
        raise RuntimeError(f"CDP error: {result['error']}")

    return result.get("result", {}).get("cookies", [])


def to_netscape(cookies):
    """生成 Netscape cookies.txt 格式 (符合 Python cookiejar _really_load 要求)"""
    lines = [
        "# Netscape HTTP Cookie File",
        "# https://curl.haxx.se/rfc/cookie-spec.html",
        "# Generated by Edge DevTools Protocol export",
        f"# Generated at: {time.strftime('%Y-%m-%d %H:%M:%S')}",
        ""
    ]

    for c in cookies:
        domain = c.get("domain", "")
        path = c.get("path", "/")
        secure = "TRUE" if c.get("secure") else "FALSE"
        expires = c.get("expires", 0)
        # expires 是秒数;0 表示 session cookie
        if expires and isinstance(expires, (int, float)) and expires > 0:
            expires = int(expires)
        else:
            expires = 0
        name = c.get("name", "")
        value = c.get("value", "")
        http_only = "#HttpOnly_" if c.get("httpOnly") else ""

        # 关键修复:initial_dot 必须与 domain_specified (有无前导 .) 匹配
        # domain 以 . 开头 → include subdomains = TRUE
        # domain 无前导 . → 只精确匹配 = FALSE
        initial_dot = "TRUE" if domain.startswith(".") else "FALSE"

        lines.append(f"{http_only}{domain}\t{initial_dot}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

    return "\n".join(lines)


def main():
    # 默认输出到工具根目录的 cookies.txt
    # 可通过命令行参数指定绝对路径
    if len(sys.argv) > 1:
        output = sys.argv[1]
    else:
        from pathlib import Path
        output = str(Path(__file__).resolve().parent / "cookies.txt")

    print("Connecting to Edge DevTools on port 9222...")
    tabs = get_tabs()
    print(f"Got {len(tabs)} tabs")

    tab = find_youtube_tab(tabs)
    if not tab:
        print("ERROR: No YouTube tab found. Open youtube.com in Edge first.")
        sys.exit(1)

    print(f"YouTube tab: {tab.get('title', '?')} ({tab.get('url', '')[:80]}...)")
    print(f"WebSocket: {tab.get('webSocketDebuggerUrl')}")

    cookies = get_cookies_via_cdp(
        tab["webSocketDebuggerUrl"],
        ["https://www.youtube.com", "https://youtube.com", "https://accounts.google.com"]
    )
    print(f"Got {len(cookies)} cookies")

    # 检查关键 cookie
    cookie_names = {c["name"] for c in cookies}
    has_login = "LOGIN_INFO" in cookie_names
    has_sid = "SID" in cookie_names or any(n.startswith("__Secure") for n in cookie_names)
    print(f"LOGIN_INFO: {has_login}, SID: {has_sid}")

    content = to_netscape(cookies)
    with open(output, "w", encoding="ascii", errors="replace") as f:
        f.write(content)
    print(f"Saved: {output}")


if __name__ == "__main__":
    main()